import React from 'react';
export function Select({ children, ...props }: any) { return <div {...props}>{children}</div>; }
export function SelectTrigger({ children, ...props }: any) { return <button {...props}>{children}</button>; }
export function SelectValue({ children, ...props }: any) { return <span {...props}>{children}</span>; }
export function SelectContent({ children, ...props }: any) { return <div {...props}>{children}</div>; }
export function SelectItem({ children, ...props }: any) { return <div {...props}>{children}</div>; }
